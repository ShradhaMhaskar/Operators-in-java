package com.tka;

public class IncrementDecrementOperators {
	public static void main(String args[]) {
		
		int i=6;
		i++;
		i--;
		System.out.println(i++);//6
		++i;
		i--;
		i++;
		System.out.println(--i);//7
		i=50;
		i++;
		--i;
		i--;
		System.out.println(i+5);//54
		++i;
		i++;
		i--;
		i++;//51
		System.out.println(i-5);//46
		i++;
		--i;
		System.out.println(i++);
		
		
	}

}
